#include "card_assist_buff_heal.h"

//===========================================================================================================================================================
// コンストラクタ
//===========================================================================================================================================================
My::CCardAssist_Buff_Heal::CCardAssist_Buff_Heal(int nPriority):CCardAssist_Buff(nPriority),
m_HealType(),
m_nHeal(INT_ZERO)
{
}

//===========================================================================================================================================================
// デストラクタ
//===========================================================================================================================================================
My::CCardAssist_Buff_Heal::~CCardAssist_Buff_Heal()
{
}

//===========================================================================================================================================================
// 初期化
//===========================================================================================================================================================
HRESULT My::CCardAssist_Buff_Heal::Init()
{
	CCardAssist_Buff::Init();

	//トリガー時のストラテジーを代入
	SetCardStrategy(new CHeal);
	return S_OK;
}

//===========================================================================================================================================================
// 終了
//===========================================================================================================================================================
void My::CCardAssist_Buff_Heal::Uninit()
{
	CCardAssist_Buff::Uninit();
}

//===========================================================================================================================================================
// 更新
//===========================================================================================================================================================
void My::CCardAssist_Buff_Heal::Update()
{
	CCardAssist_Buff::Update();
}

//===========================================================================================================================================================
// 描画
//===========================================================================================================================================================
void My::CCardAssist_Buff_Heal::Draw()
{
	CCardAssist_Buff::Draw();
}

//===========================================================================================================
//固有情報の読み込み
//===========================================================================================================
void My::CCardAssist_Buff_Heal::LoadUniqueInfo(CCard_Client::Param param)
{
	//親の固有読み込み
	My::CCardAssist_Buff::LoadUniqueInfo(param);

	//回復ステータスの読み込み
	m_HealType = (HealType)param.Healtype;	//バフの種類
	m_nHeal = param.nHeal;					//回復値
}

//===========================================================================================================
//キャストをしたかの確認
//===========================================================================================================
bool My::CCardAssist_Buff_Heal::IsCast(CDuelCharacter* duel)
{
	return My::CCardAssist::IsCast(duel);
}