//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CPaseudoCardIllust::CPaseudoCardIllust(int nPriority):CObject2D(nPriority)
{
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CPaseudoCardIllust::~CPaseudoCardIllust()
{
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
HRESULT My::CPaseudoCardIllust::Init()
{
	//親クラスの初期化処理を呼ぶ
	CObject2D::Init();

	//テクスチャ座標設定
	SetTexPos(VEC2_RESET_ONE);

	//カラー取得
	D3DXCOLOR col = GetColor();

	col = { 0.8f,0.8f,0.8f,1.0f };

	//カラーを代入
	SetColor(col);

	//頂点設定
	SetVtx();
	return S_OK;
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CPaseudoCardIllust::Uninit()
{
	//親クラスの終了処理を呼ぶ
	CObject2D::Uninit();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CPaseudoCardIllust::Update()
{
	// 親クラスの更新処理を呼ぶ
	CObject2D::Update();

	//頂点設定
	SetVtx();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CPaseudoCardIllust::Draw()
{
	// 親クラスの描画処理を呼ぶ
	CObject2D::Draw();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CPaseudoCardIllust* My::CPaseudoCardIllust::Create(D3DXVECTOR3 pos, D3DXVECTOR2 size)
{
	CPaseudoCardIllust* pObject = new CPaseudoCardIllust();

	//nullならnullを返す
	if (pObject == nullptr) { return nullptr; }

	//pos設定
	pObject->SetPos(pos);

	pObject->SetSize(size);

	//初期化
	pObject->Init();

	return pObject;
}
