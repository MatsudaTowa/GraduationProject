#include "card_frame_use_font.h"

//===========================================================================================================================================================
// コンストラクタ
//===========================================================================================================================================================
My::CCardFrameUseFont::CCardFrameUseFont(int nPriority):CCardFrame(nPriority),
m_pFontManager(nullptr),
m_offsetpos(VEC3_RESET_ZERO)
{
}

//===========================================================================================================================================================
// デストラクタ
//===========================================================================================================================================================
My::CCardFrameUseFont::~CCardFrameUseFont()
{
	if (m_pFontManager != nullptr)
	{
		m_pFontManager->Uninit();
		delete m_pFontManager;
		m_pFontManager = nullptr;
	}
}

//===========================================================================================================================================================
// 初期化
//===========================================================================================================================================================
HRESULT My::CCardFrameUseFont::Init()
{
	CCardFrame::Init();
	return S_OK;
}

//===========================================================================================================================================================
// 終了
//===========================================================================================================================================================
void My::CCardFrameUseFont::Uninit()
{
	CCardFrame::Uninit();
}

//===========================================================================================================================================================
// 更新
//===========================================================================================================================================================
void My::CCardFrameUseFont::Update()
{
	CCardFrame::Update();

	if (m_pFontManager != nullptr)
	{
		D3DXVECTOR3 screen_pos = ConvertToScreenPos(GET_CAMERA(GET_CAMERA_IDX), GetPos()); //スクリーン座標に変換

		screen_pos.x += m_offsetpos.x;
		screen_pos.y += m_offsetpos.y;

		m_pFontManager->UpdatePos(screen_pos);

		std::vector<CFont*> list = m_pFontManager->GetList();
		for (auto& itr : list)
		{
			if (itr == nullptr) { continue; }
			CCard::ZONE current_zone = GetCard()->GetCurrentZone();

			// 山札時はコストを表示しないように TODO:今後はここの条件式を見直す必要あり
			if (current_zone == CCard::DECK || current_zone == CCard::CEMETERY)
			{
				itr->SetisDraw(false);
			}
			else
			{
				itr->SetisDraw(true);
			}
		}
	}
}
