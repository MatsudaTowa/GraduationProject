//===========================================================================================================================================================
// コンストラクタ
//===========================================================================================================================================================
My::CCardFrameUseFont::CCardFrameUseFont(int nPriority):CCardFrame(nPriority),
m_pFontManager(nullptr),
m_offsetpos(VEC3_RESET_ZERO)
{
}

//===========================================================================================================================================================
// デストラクタ
//===========================================================================================================================================================
My::CCardFrameUseFont::~CCardFrameUseFont()
{
	if (m_pFontManager != nullptr)
	{
		m_pFontManager->Uninit();
		delete m_pFontManager;
		m_pFontManager = nullptr;
	}
}

//===========================================================================================================================================================
// 初期化
//===========================================================================================================================================================
HRESULT My::CCardFrameUseFont::Init()
{
	CCardFrame::Init();
	return S_OK;
}

//===========================================================================================================================================================
// 終了
//===========================================================================================================================================================
void My::CCardFrameUseFont::Uninit()
{
	CCardFrame::Uninit();
}

//===========================================================================================================================================================
// 更新
//===========================================================================================================================================================
void My::CCardFrameUseFont::Update()
{
	CCardFrame::Update();

	if (m_pFontManager != nullptr)
	{
		D3DXVECTOR3 offset_pos = GetPos(); //スクリーン座標に変換

		offset_pos.x += m_offsetpos.x;
		offset_pos.y += m_offsetpos.y;

		m_pFontManager->UpdatePos(offset_pos);

		std::vector<CFont*> list = m_pFontManager->GetList();
		for (auto& itr : list)
		{
			if (itr == nullptr) { continue; }

			itr->SetisDraw(GetisDraw());
		}
	}
}
