#include "wait_next_UI.h"

//無名空間
namespace
{
	const D3DXVECTOR2 UI_SIZE{ 50.0f, 30.0f };	//サイズ
	const std::string TEXTURE_PATH =	//テクスチャパス
	{
		{ "data\\TEXTURE\\WatingUI\\NEXT.png" },
	};
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CWaitNextUI::CWaitNextUI(int nPriority):CObject2D(nPriority)
{
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CWaitNextUI::~CWaitNextUI()
{
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
HRESULT My::CWaitNextUI::Init()
{
	//親クラスの初期化処理を呼ぶ
	CObject2D::Init();

	//テクスチャ情報の取得
	CTexture* pTexture = CManager::GetInstance()->GetTexture();

	//テクスチャ設定
	BindTexture(pTexture->GetAddress(pTexture->Regist(TEXTURE_PATH)));

	//自分自身のサイズ取得
	D3DXVECTOR2 size = UI_SIZE;

	//テクスチャ座標設定
	SetTexPos(VEC2_RESET_ONE);

	//サイズを代入
	SetSize(size);

	//カラー取得
	D3DXCOLOR col = GetColor();

	col = { 0.8f,0.8f,0.8f,1.0f };

	//カラーを代入
	SetColor(col);

	//頂点設定
	SetVtx();

	return S_OK;
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CWaitNextUI::Uninit()
{	
	//親クラスの終了処理を呼ぶ
	CObject2D::Uninit();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CWaitNextUI::Update()
{
	// 親クラスの更新処理を呼ぶ
	CObject2D::Update();

	//頂点設定
	SetVtx();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
void My::CWaitNextUI::Draw()
{
	// 親クラスの描画処理を呼ぶ
	CObject2D::Draw();
}

//===========================================================================================================================================================
// 
//===========================================================================================================================================================
My::CWaitNextUI* My::CWaitNextUI::Create(D3DXVECTOR3 pos)
{
	CWaitNextUI* pObject = new CWaitNextUI();

	//nullならnullを返す
	if (pObject == nullptr) { return nullptr; }

	//pos設定
	pObject->SetPos(pos);

	//初期化
	pObject->Init();

	return pObject;
}
