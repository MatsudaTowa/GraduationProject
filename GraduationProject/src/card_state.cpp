//===========================================================================================================
// 
// ステイステート(カード効果発動待機)
// 
//===========================================================================================================

//=======================================================================================
// 初期化
//=======================================================================================
void My::CCardStateStay::Init(CCard* cpy)
{
	// カウントを初期化
	m_Staycount = 0;

	// ステータスを取得
	CActiveSceneCharacter::Status status = CActiveSceneManager::GetInstance()->GetPlayer()->GetStatus();

	if (CManager::GetInstance()->GetMouse()->GetArea() == CInputMouse::AREA::CENTER ||
		status.energy < cpy->GetParameter().cost)
	{// 真ん中エリアだった場合
		cpy->ChangeState(CCardState::CARD_NEUTRAL);
	}
	else
	{// そのほかのエリアの場合

		// コスト分エナジーを減らす
		status.energy -= cpy->GetParameter().cost;

		// エナジーを設定
		CActiveSceneManager::GetInstance()->GetPlayer()->SetStatus(status);

		// ターゲットアローを生成
		cpy->SetTargetArrow(CTargetArrow::Create(CInputMouse::AREA::DOWN, cpy->GetTarget()));
	}

	
}

//=======================================================================================
// 更新
//=======================================================================================
void My::CCardStateStay::Update(CCard* cpy)
{
	if (cpy == nullptr)
		return;

	if (m_Staycount >= STAY_TIME)
	{// カウントが設定された時間を超えたら

		// トリガー状態にする
		cpy->ChangeState(CCardState::CARD_STATE::CARD_TRIGGER);
	}

	// カウントを進める
	m_Staycount++;
}

//===========================================================================================================
// 
// トリガーステート(カード効果発動)
// 
//===========================================================================================================

//=======================================================================================
// 初期化
//=======================================================================================
void My::CCardStateTrigger::Init(CCard* cpy)
{
	if (cpy == nullptr)
		return;

	CActiveSceneManager::GetInstance()->GetAreaManager()->CardTrigger(cpy->GetTarget());

	// トリガーされた際に消去する
	cpy->GetTargetArrow()->Uninit();
}
