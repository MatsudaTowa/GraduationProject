//===========================================================================================================
// 
// ステイステート(カード効果発動待機)
// 
//===========================================================================================================

//=======================================================================================
// 初期化
//=======================================================================================
void My::CCardStateStay::Init()
{
	// カウントを初期化
	m_Staycount = 0;
}

//=======================================================================================
// 更新
//=======================================================================================
void My::CCardStateStay::Update(CCard* cpy)
{
	if (cpy == nullptr)
		return;

	if (m_Staycount >= STAY_TIME)
	{// カウントが設定された時間を超えたら

		// トリガー状態にする
		cpy->ChangeState(CCardState::CARD_STATE::CARD_TRIGGER);
	}

	// カウントを進める
	m_Staycount++;
}

//===========================================================================================================
// 
// トリガーステート(カード効果発動)
// 
//===========================================================================================================

//=======================================================================================
// 初期化
//=======================================================================================
void My::CCardStateTrigger::Init(CCard* cpy)
{
	if (cpy == nullptr)
		return;

	// トリガーしたことをわかりやすくするため今だけ位置を変えている
	D3DXVECTOR3 pos = cpy->GetPos();
	pos.x += 20.0f;
	cpy->SetPos(pos);
}
