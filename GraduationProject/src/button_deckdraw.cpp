#include "button_deckdraw.h"
#include "active_scene_player_state.h"

//宣言
const std::string My::CButtonDeckDraw::TEX_NAME = "data\\TEXTURE\\DRAW.png";

//==================================================================================================================
// コンストラクタ
//==================================================================================================================
My::CButtonDeckDraw::CButtonDeckDraw(int nPriority)
{
}

//==================================================================================================================
// デストラクタ
//==================================================================================================================
My::CButtonDeckDraw::~CButtonDeckDraw()
{
}

//==================================================================================================================
// 初期化
//==================================================================================================================
HRESULT My::CButtonDeckDraw::Init()
{
	
	SetColor(COLOR_WHITE);
	BindTexture(GET_TEXTURE->GetAddress(GET_TEXTURE->Regist(CButtonDeckDraw::TEX_NAME)));
	CButton::Init();

	return S_OK;
}

//==================================================================================================================
// 終了
//==================================================================================================================
void My::CButtonDeckDraw::Uninit()
{
	CButton::Uninit();
}

//==================================================================================================================
// 更新
//==================================================================================================================
void My::CButtonDeckDraw::Update()
{
	CButton::Update();
}

//==================================================================================================================
// 描画
//==================================================================================================================
void My::CButtonDeckDraw::Draw()
{
	CButton::Draw();
}

//==================================================================================================================
// マウスイベント
//==================================================================================================================
bool My::CButtonDeckDraw::ProcessMouseEvent(CPlayerDuelState* state)
{
	// 標準の色に設定
	SetColor(COLOR_WHITE);
	// 当たっているかどうか
	bool ishit = CButton::ProcessMouseEvent();
	
	if (ishit)
	{
		// 範囲に入っているかわかりやすいように色を変える
		SetColor(COLOR_RED);
		
		// ボタンが押された時の処理
		ButtonTrigger(state);
		
		return true;
	}

	return false;
}

//==================================================================================================================
// ボタンが押された時の処理
//==================================================================================================================
void My::CButtonDeckDraw::ButtonTrigger()
{

}

//==================================================================================================================
// ボタンが押された時の処理
//==================================================================================================================
void My::CButtonDeckDraw::ButtonTrigger(CPlayerDuelState* state)
{
	if (GET_INPUT_MOUSE->GetTrigger(0))
	{
		// TODO : 音の鳴らすタイミングを考える
		CManager::GetInstance()->GetSound()->PlaySound(CSound::SOUND_LABEL_SE_CARD_DRAW);

		CHand* pHand = state->GetHand();
		pHand->DeckDraw(state);
	}
}

//==================================================================================================================
// 生成
//==================================================================================================================
My::CButtonDeckDraw* My::CButtonDeckDraw::Create(D3DXVECTOR3 pos, D3DXVECTOR2 size)
{
	CButtonDeckDraw* pButton = new CButtonDeckDraw;

	pButton->SetPos(pos);
	pButton->SetSize(size);

	pButton->Init();

	return pButton;
}