#include "life_changer.h"

//==============================================================
//コンストラクタ
//==============================================================
My::CLife_changer::CLife_changer() :
	m_fLife(FLOAT_ZERO),
	m_fLife_Max(FLOAT_ZERO),
	m_fRaito(FLOAT_ZERO)
{
}

//==============================================================
//デストラクタ
//==============================================================
My::CLife_changer::~CLife_changer()
{

}

//==============================================================
//初期化
//==============================================================
HRESULT My::CLife_changer::Init()
{
	return S_OK;
}

//==============================================================
//終了
//==============================================================
void My::CLife_changer::Uninit()
{
	m_fLife = FLOAT_ZERO;
	m_fLife_Max = FLOAT_ZERO;
	m_fRaito = FLOAT_ZERO;
}

//==============================================================
//更新
//==============================================================
void My::CLife_changer::Update()
{
	CInputKeyboard* pKey =  CManager::GetInstance()->GetKeyboard();

	//体力のあれこれ。（ポリゴンに伝える。ひとまずここでキーボード入力での操作）
	//HP増加
	if (pKey->GetTrigger(DIK_L))
	{
		ApplyHeal(1.0f);
	}

	//HP減少
	else if (pKey->GetTrigger(DIK_K))
	{
		ApplyDamage(1.0f);
	}

	m_fRaito = (m_fLife / m_fLife_Max);
}

//==============================================================
//生成
//==============================================================
My::CLife_changer* My::CLife_changer::Create()
{
	CLife_changer* Change = nullptr;
	Change = new CLife_changer();
	Change->Init();
	return Change;
}

